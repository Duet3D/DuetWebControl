// ─── Loading ─────────────────────────────────────────────────────────

/**
 * Load and initialise a single DWC plugin by ID.
 *
 * Checks built-in plugins first, then falls back to external.
 *
 * @param id Plugin ID
 * @param saveSettings Whether to persist the enabled state
 */
export async function loadDwcPlugin(id: string, saveSettings = true): Promise<void> {
	if (loadedPlugins.has(id)) {
		console.warn(`Plugin "${id}" is already loaded`);
		return;
	}

	const builtIn = builtInPlugins.find(p => p.id === id);
	if (builtIn) {
		await loadBuiltInPlugin(builtIn);
	} else {
		await loadExternalPlugin(id);
	}

	if (saveSettings) {
		useSettingsStore().dwcPluginLoaded(id);
	}

	Events.emit("dwcPluginLoaded", id);
}

/**
 * Load all enabled DWC plugins, reporting progress via events.
 */
export async function loadDwcPlugins(): Promise<void> {
	const settingsStore = useSettingsStore();

	if (settingsStore.enabledPlugins.length === 0) {
		return;
	}

	Events.emit("dwcPluginsLoading", [...settingsStore.enabledPlugins]);

	for (const id of settingsStore.enabledPlugins) {
		try {
			await loadDwcPlugin(id, false);
		} catch (e) {
			console.warn(`Failed to load plugin "${id}":`, e);
			Events.emit("dwcPluginLoadError", { id, error: e });
		}
	}

	Events.emit("dwcPluginsLoaded", [...settingsStore.enabledPlugins]);
}

/**
 * Unload a plugin (best-effort — removes tracking and settings entry)
 * @param id Plugin ID
 */
export async function unloadDwcPlugin(id: string): Promise<void> {
	if (!loadedPlugins.has(id)) {
		return;
	}

	loadedPlugins.delete(id);

	useSettingsStore().disableDwcPlugin(id);

	Events.emit("dwcPluginUnloaded", id);
}

// ─── Built-in plugin loading ─────────────────────────────────────────

/**
 * Load a built-in plugin by executing its dynamic import.
 * The module's side effects handle all registration.
 */
async function loadBuiltInPlugin(plugin: DwcPlugin): Promise<void> {
	await plugin.loadDwcResources();
	loadedPlugins.add(plugin.id);
}

// ─── External plugin loading ─────────────────────────────────────────

/**
 * Load an external plugin by fetching its JS/CSS from the machine.
 *
 * External plugins are IIFE bundles compiled with DWC's shared libraries
 * (vue, vue-router, pinia, DWC's own API) marked as externals. At runtime
 * those resolve to properties on `window.DWC`, so the plugin code can call
 * the same registration functions as built-in plugins.
 */
async function loadExternalPlugin(id: string): Promise<void> {
	const machineStore = useMachineStore();
	const machinePlugin = machineStore.model.plugins.get(id);

	if (!machinePlugin) {
		throw new Error(`Plugin "${id}" not found in built-in registry or machine plugins`);
	}

	// Validate manifest
	if (!checkManifest(machinePlugin)) {
		throw new Error(`Plugin "${id}" has an invalid manifest`);
	}

	// Version compatibility check
	if (machinePlugin.dwcVersion && !checkVersion(packageInfo.version, machinePlugin.dwcVersion)) {
		throw new Error(
			`Plugin "${id}" requires DWC version ${machinePlugin.dwcVersion}, ` +
			`current is ${packageInfo.version}`
		);
	}

	// Check dependencies
	for (const dep of machinePlugin.dwcDependencies) {
		if (!loadedPlugins.has(dep)) {
			throw new Error(`Plugin "${id}" depends on "${dep}" which is not loaded`);
		}
	}

	// Separate JS and CSS files
	const jsFiles = machinePlugin.dwcFiles.filter((f: string) => f.endsWith(".js"));
	const cssFiles = machinePlugin.dwcFiles.filter((f: string) => f.endsWith(".css"));

	if (jsFiles.length === 0) {
		throw new Error(`Plugin "${id}" has no JS entry in dwcFiles`);
	}

	const baseURL = process.env.BASE_URL ?? '/';

	// Load CSS first
	for (const cssFile of cssFiles) {
		await loadExternalCSS(id, baseURL + cssFile);
	}

	// Load and execute JS
	for (const jsFile of jsFiles) {
		await loadExternalJS(id, baseURL + jsFile);
	}

	loadedPlugins.add(id);
}

/**
 * Load a CSS file for an external plugin by injecting a <link> element.
 * The browser fetches the resource; the promise resolves/rejects via load/error events.
 */
function loadExternalCSS(pluginId: string, url: string): Promise<void> {
	return new Promise<void>((resolve, reject) => {
		const link = document.createElement("link");
		link.rel = "stylesheet";
		link.setAttribute("data-dwc-plugin", pluginId);
		link.href = url;
		link.onload = () => resolve();
		link.onerror = () => reject(new Error(`Failed to load CSS "${url}" for plugin "${pluginId}"`));
		document.head.appendChild(link);
	});
}

/**
 * Load a JS file for an external plugin by injecting a <script> element.
 * The browser fetches and executes the IIFE bundle; the promise resolves/rejects via load/error events.
 * The script accesses DWC APIs via `window.DWC` (set up by exposeGlobalAPI).
 */
function loadExternalJS(pluginId: string, url: string): Promise<void> {
	return new Promise<void>((resolve, reject) => {
		const script = document.createElement("script");
		script.setAttribute("data-dwc-plugin", pluginId);
		script.src = url;
		script.onload = () => resolve();
		script.onerror = () => reject(new Error(`Failed to load JS "${url}" for plugin "${pluginId}"`));
		document.head.appendChild(script);
	});
}

// ─── Global API for external plugins ─────────────────────────────────

/**
 * Expose DWC's plugin API on `window.DWC` so that external plugin bundles
 * (compiled with these modules marked as externals) can access them at runtime.
 *
 * External plugins are built as IIFE bundles with rollup externals like:
 *   external: ["DuetWebControl", "vue", "vue-router", "pinia", ...]
 *   globals:  { "DuetWebControl": "DWC", "vue": "DWC.Vue", ... }
 *
 * This gives external plugins the same import experience as built-in ones.
 */
function exposeGlobalAPI() {
	(window as any).DWC = {
		// Plugin registration
		registerRoute,
		registerCategory,
		registerPluginContextMenuItem,

		// Plugin data
		registerPluginData,
		setPluginData,
		PluginDataType,

		// Stores
		useSettingsStore,
		useMachineStore,
		useCacheStore,
		useUiStore,
		ContextMenuType,

		// Events
		Events,

		// Vue ecosystem (mapped as globals for external plugin builds)
		Vue,
		VueRouter,
		Pinia,
		VueI18n,
		ObjectModel,
		Connectors,

		// i18n
		i18n,
	};
}
