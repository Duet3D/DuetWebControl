// ─── Manifest validation ─────────────────────────────────────────────

/**
 * Validate a plugin manifest.
 * @param manifest Plugin manifest to check
 * @returns Whether the manifest is valid
 */
export function checkManifest(manifest: { id: string; name: string; author: string; version: string }): boolean {
	if (!manifest.id || manifest.id.trim() === "" || manifest.id.length > 32) {
		console.warn("Invalid plugin identifier");
		return false;
	}
	if (manifest.id.split("").some(c => !/[a-zA-Z0-9 .\-_]/.test(c))) {
		console.warn("Illegal plugin identifier");
		return false;
	}
	if (!manifest.name || manifest.name.trim() === "" || manifest.name.length > 64) {
		console.warn("Invalid plugin name");
		return false;
	}
	if (manifest.name.split("").some(c => !/[a-zA-Z0-9 .\-_]/.test(c))) {
		console.warn("Illegal plugin name");
		return false;
	}
	if (!manifest.author || manifest.author.trim() === "") {
		console.warn("Missing author");
		return false;
	}
	if (!manifest.version || manifest.version.trim() === "") {
		console.warn("Missing version");
		return false;
	}
	return true;
}

/**
 * Perform a version compatibility check.
 * Compares version segments up to the shorter of the two strings.
 * @param actual Actual version (e.g. "3.6.0")
 * @param required Required version (e.g. "3.6")
 * @returns Whether the actual version satisfies the required version
 */
export function checkVersion(actual: string, required: string): boolean {
	if (!required) {
		return true;
	}
	const actualParts = actual.split(/[+.\-ab]/);
	const requiredParts = required.split(/[+.\-ab]/);
	for (let i = 0; i < Math.min(actualParts.length, requiredParts.length); i++) {
		if (actualParts[i] !== requiredParts[i]) {
			return false;
		}
	}
	return true;
}

// ─── State ───────────────────────────────────────────────────────────

/**
 * Set of currently loaded plugin IDs
 */
const loadedPlugins = new Set<string>();

/**
 * Vue Router instance, set during initialisation
 */
let _router: Router | null = null;

/**
 * Menu categories registered by plugins
 */
export interface MenuCategory {
	icon: string;
	caption: string | (() => string);
	translated: boolean;
	pages: Array<MenuItem>;
}

/**
 * Menu item registered by a plugin
 */
export interface MenuItem {
	icon: string;
	caption: string | (() => string);
	path: string;
	component: Component;
	translated?: boolean;
	condition?: boolean | (() => boolean);
}

const _menuCategories = new Map<string, MenuCategory>();

// ─── Initialisation ──────────────────────────────────────────────────

/**
 * Initialise the plugin system. Must be called once during app startup
 * before any plugins are loaded.
 *
 * Sets up the global `window.DWC` object so that external plugins can
 * access DWC APIs at runtime.
 *
 * @param router Vue Router instance
 */
export function initPluginSystem(router: Router) {
	_router = router;
	exposeGlobalAPI();
}

// ─── Plugin registration API ─────────────────────────────────────────
// These functions are called directly by plugins (both built-in and external).

/**
 * Register a new route and menu item.
 *
 * Follows the same convention as the previous DWC:
 *   registerRoute(Component, { CategoryName: { PageName: { icon, caption, path, condition? } } })
 *
 * @param component Vue component to render
 * @param route Route descriptor: { [category]: { [name]: { icon, caption, path, condition?, translated? } } }
 */
export function registerRoute(
	component: Component,
	route: Record<string, Record<string, { icon: string; caption: string | (() => string); path: string; condition?: boolean | (() => boolean); translated?: boolean }>>
) {
	if (!_router) {
		throw new Error("Plugin system not initialised");
	}

	const category = Object.keys(route)[0];
	const name = Object.keys(route[category])[0];
	const descriptor = route[category][name];

	// Build menu item
	const menuItem: MenuItem = {
		icon: descriptor.icon,
		caption: descriptor.caption,
		path: descriptor.path,
		component,
		translated: descriptor.translated ?? false,
		condition: descriptor.condition ?? true,
	};

	// Ensure category exists
	if (!_menuCategories.has(category)) {
		_menuCategories.set(category, {
			icon: "mdi-puzzle",
			caption: `menu.${category.toLowerCase()}.caption`,
			translated: false,
			pages: [],
		});
	}

	// Add to category
	_menuCategories.get(category)!.pages.push(menuItem);

	// Register vue-router route
	_router.addRoute({
		path: descriptor.path,
		component,
	} as RouteRecordRaw);
}

/**
 * Register a new menu category
 * @param name Internal name of the category
 * @param icon MDI icon string
 * @param caption Display caption (i18n key or getter function)
 * @param translated Whether the caption is already translated
 */
export function registerCategory(name: string, icon: string, caption: string | (() => string), translated = false) {
	if (!_menuCategories.has(name)) {
		_menuCategories.set(name, {
			icon,
			caption,
			translated,
			pages: [],
		});
	}
}

/**
 * Register a context menu item (e.g., on the job file list)
 * @param name Caption of the context menu item
 * @param path Optional route path to navigate to on click
 * @param icon MDI icon string
 * @param action Global event to trigger on click
 * @param contextMenuType Target of the context menu item
 */
export function registerPluginContextMenuItem(name: string | (() => string), path: string | undefined, icon: string, action: string, contextMenuType: ContextMenuType) {
	useUiStore().registerContextMenuItem({
		name,
		path,
		icon,
		action,
		contextMenuType,
	} as ContextMenuItem);
}

