// #region Initialisation
/**
 * Initialise the plugin system. Must be called once during app startup
 * before any plugins are loaded.
 *
 * Sets up the global `window.DWC` object so that external plugins can
 * access DWC APIs at runtime, and registers the public DWC component
 * palette + Vuetify components used by core globally on the app so
 * external plugin templates can resolve them by name.
 *
 * @param app Vue app instance
 * @param router Vue Router instance
 */
export function initPluginSystem(app: App, router: Router) {
	_app = app;
	_router = router;
	// Vuetify core components (the subset DWC's own templates use) are eager - they're already
	// in the main bundle anyway, registering them globally so plugin templates can resolve
	// `<v-foo>` by name costs nothing. The Vuetify extras + DWC's own components load lazily
	// on first external-plugin arrival via ensurePluginExtras()
	for (const [name, component] of Object.entries(vuetifyCoreComponents)) {
		app.component(name, component);
	}
	exposeGlobalAPI();
}

let _app: App | null = null;
let _pluginExtrasLoaded = false;

/**
 * Lazy one-shot: load + globally register the Vuetify components NOT referenced anywhere
 * under src/, plus every DWC component under src/components/. Triggered on the first
 * external-plugin load so users with no external plugins never pay for the extras chunks.
 */
async function ensurePluginExtras(): Promise<void> {
	if (_pluginExtrasLoaded || !_app) {
		return;
	}
	_pluginExtrasLoaded = true;

	const [vuetifyExtrasMod, dwcComponentsMod] = await Promise.all([
		import("virtual:dwc-vuetify-extras"),
		import("virtual:dwc-components"),
	]);

	for (const [name, component] of Object.entries(vuetifyExtrasMod.default)) {
		_app.component(name, component);
	}
	for (const [name, component] of Object.entries(dwcComponentsMod.default)) {
		_app.component(name, component);
	}

	// Surface on window.DWC so plugins built with explicit imports resolve at runtime:
	//   import { VFoo } from "vuetify/components"          -> DWC.VuetifyComponents.VFoo
	//   import { FileList } from "DuetWebControl/components" -> DWC.Components.FileList
	// Fill the maps in place rather than reassigning: window.DWC is frozen after exposeGlobalAPI,
	// so its top-level keys can't be replaced - but the nested maps stay mutable (shallow freeze)
	const dwc = window.DWC;
	if (dwc) {
		Object.assign(dwc.VuetifyComponents, vuetifyExtrasMod.default);
		Object.assign(dwc.Components, dwcComponentsMod.default);
	}
}

