/**
 * plugins/index.ts
 *
 * DWC Plugin Loader
 *
 * Handles loading both built-in and external plugins:
 *
 * Built-in plugins are part of the same Vite build. They are auto-discovered
 * at build time by vite-plugin-dwc-plugins and lazily imported. Because they
 * share the module graph, they simply import what they need directly:
 *
 *   import { registerRoute } from "@/plugins";
 *   import MyPage from "./MyPage.vue";
 *   registerRoute(MyPage, { Plugins: { MyPage: { icon: "mdi-...", caption: "...", path: "/Plugins/MyPage" } } });
 *
 * External plugins are precompiled IIFE bundles fetched at runtime from the
 * machine. They are built with DWC's shared libraries marked as externals,
 * mapped to `window.DWC`. This lets them use the same API:
 *
 *   const { registerRoute } = DWC;
 *   registerRoute(MyPage, { ... });
 *
 * The global `window.DWC` object is set up by `initPluginSystem()` and exposes
 * the plugin registration functions, stores, Vue, vue-router, and i18n.
 */

