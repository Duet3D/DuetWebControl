// #region Manifest validation
/**
 * Validate a plugin manifest.
 * @param manifest Plugin manifest to check
 * @returns Whether the manifest is valid
 */
export function checkManifest(manifest: { id: string; name: string; author: string; version: string; sbcPermissions?: Iterable<string> }): boolean {
	if (!manifest.id || manifest.id.trim() === "" || manifest.id.length > 32) {
		console.warn("Invalid plugin identifier");
		return false;
	}
	if (manifest.id.split("").some(c => !/[a-zA-Z0-9 .\-_]/.test(c))) {
		console.warn("Illegal plugin identifier");
		return false;
	}
	if (!manifest.name || manifest.name.trim() === "" || manifest.name.length > 64) {
		console.warn("Invalid plugin name");
		return false;
	}
	if (manifest.name.split("").some(c => !/[a-zA-Z0-9 .\-_]/.test(c))) {
		console.warn("Illegal plugin name");
		return false;
	}
	if (!manifest.author || manifest.author.trim() === "") {
		console.warn("Missing author");
		return false;
	}
	if (!manifest.version || manifest.version.trim() === "") {
		console.warn("Missing version");
		return false;
	}
	if (manifest.sbcPermissions) {
		const supported = Object.keys(SbcPermission);
		for (const permission of manifest.sbcPermissions) {
			if (!supported.includes(permission)) {
				console.warn(`Unsupported SBC permission ${permission}`);
				return false;
			}
		}
	}
	return true;
}

/**
 * Perform a version compatibility check.
 * Compares version segments up to the shorter of the two strings.
 * @param actual Actual version (e.g. "3.6.0")
 * @param required Required version (e.g. "3.6")
 * @returns Whether the actual version satisfies the required version
 */
export function checkVersion(actual: string, required: string): boolean {
	if (!required) {
		return true;
	}
	const actualParts = actual.split(/[+.\-ab]/);
	const requiredParts = required.split(/[+.\-ab]/);
	for (let i = 0; i < Math.min(actualParts.length, requiredParts.length); i++) {
		if (actualParts[i] !== requiredParts[i]) {
			return false;
		}
	}
	return true;
}

