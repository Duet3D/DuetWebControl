/**
 * Merge a plugin's locale messages into DWC's shared i18n instance under
 * `plugins.<pluginId>.*`. Pass a per-locale map - typically built from JSON
 * imports the plugin ships alongside its source:
 *
 * ```ts
 * import en from "./i18n/en.json";
 * import de from "./i18n/de.json";
 * registerPluginMessages("endstopsMonitor", { en, de });
 * // -> keys now resolvable as `plugins.endstopsMonitor.<key>` for every locale
 * ```
 *
 * Each call is additive - re-registering replaces only the leaf keys the new
 * map provides; other plugins' messages and DWC's own keys are untouched
 */
export function registerPluginMessages(pluginId: string, messagesPerLocale: Record<string, Record<string, unknown>>) {
	for (const [locale, messages] of Object.entries(messagesPerLocale)) {
		i18n.global.mergeLocaleMessage(locale, { plugins: { [pluginId]: messages } });
	}
}

