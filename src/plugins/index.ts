// #region External plugin loading
/**
 * Load an external plugin by fetching its JS/CSS from the machine.
 *
 * External plugins are IIFE bundles compiled with DWC's shared libraries
 * (vue, vue-router, pinia, DWC's own API) marked as externals. At runtime
 * those resolve to properties on `window.DWC`, so the plugin code can call
 * the same registration functions as built-in plugins.
 */
async function loadExternalPlugin(id: string): Promise<void> {
	// External plugin templates may use any Vuetify component (not just the subset DWC core
	// imports) and any DWC component (FileList, CodeButton, ...). Lazy-load + globally
	// register both extras chunks once, on first external load, so subsequent plugins
	// resolve them without re-fetching
	await ensurePluginExtras();

	const machineStore = useMachineStore();
	const machinePlugin = machineStore.model.plugins.get(id);

	if (!machinePlugin) {
		throw new Error(`Plugin "${id}" not found in built-in registry or machine plugins`);
	}

	// Validate manifest
	if (!checkManifest(machinePlugin)) {
		throw new Error(`Plugin "${id}" has an invalid manifest`);
	}

	// Version compatibility check
	if (machinePlugin.dwcVersion && !checkVersion(packageInfo.version, machinePlugin.dwcVersion)) {
		throw new Error(
			`Plugin "${id}" requires DWC version ${machinePlugin.dwcVersion}, ` +
			`current is ${packageInfo.version}`
		);
	}

	// Check dependencies
	for (const dep of machinePlugin.dwcDependencies) {
		if (!isPluginLoaded(dep)) {
			throw new Error(`Plugin "${id}" depends on "${dep}" which is not loaded`);
		}
	}

	// Separate JS and CSS files
	const jsFiles = machinePlugin.dwcFiles.filter((f: string) => f.endsWith(".js"));
	const cssFiles = machinePlugin.dwcFiles.filter((f: string) => f.endsWith(".css"));

	// SBC-only plugins (e.g. DuetPiManagementPlugin) have no DWC JS - that's a valid configuration,
	// the plugin runs entirely on the SBC. Treat the load as a no-op so it can still be marked
	// active and recorded in the loaded set; the caller may follow up with startSbcPlugin() to
	// actually launch the backend
	if (jsFiles.length === 0) {
		loadedPlugins.add(id);
		return;
	}

	const baseURL = import.meta.env.BASE_URL;

	// Load CSS first
	for (const cssFile of cssFiles) {
		await loadExternalCSS(id, baseURL + cssFile);
	}

	// Load and execute JS
	for (const jsFile of jsFiles) {
		await loadExternalJS(id, baseURL + jsFile);
	}

	loadedPlugins.add(id);
}

/**
 * Load a CSS file for an external plugin by injecting a <link> element.
 * The browser fetches the resource; the promise resolves/rejects via load/error events.
 */
function loadExternalCSS(pluginId: string, url: string): Promise<void> {
	return new Promise<void>((resolve, reject) => {
		const link = document.createElement("link");
		link.rel = "stylesheet";
		link.setAttribute("data-dwc-plugin", pluginId);
		link.href = url;
		link.onload = () => resolve();
		link.onerror = () => reject(new Error(`Failed to load CSS "${url}" for plugin "${pluginId}"`));
		document.head.appendChild(link);
	});
}

/**
 * Load a JS file for an external plugin by injecting a <script> element.
 * The browser fetches and executes the IIFE bundle; the promise resolves/rejects via load/error events.
 * The script accesses DWC APIs via `window.DWC` (set up by exposeGlobalAPI).
 */
function loadExternalJS(pluginId: string, url: string): Promise<void> {
	return new Promise<void>((resolve, reject) => {
		const script = document.createElement("script");
		script.setAttribute("data-dwc-plugin", pluginId);
		script.src = url;
		script.onload = () => resolve();
		script.onerror = () => reject(new Error(`Failed to load JS "${url}" for plugin "${pluginId}"`));
		document.head.appendChild(script);
	});
}

